#!/usr/bin/env node

/**
 * Nightly NL Design System token sync: upstream theme to nldesign vocabulary.
 *
 * SPDX-License-Identifier: EUPL-1.2
 * SPDX-FileCopyrightText: 2026 Conduction B.V. <info@conduction.nl>
 *
 * Replaces the raw dump `scripts/generate-tokens.mjs` used to write. That dump
 * put upstream palette steps under `--nldesign-*` names nothing reads, so a
 * set rendered as Rijkshuisstijl, and it overwrote sets that had been resolved
 * by hand (zwolle, #526 and #982). This script instead, per organisation in
 * `proprietary/` of a nl-design-system/themes checkout:
 *
 *   1. classifies the shipped set. Only an upstream-managed set is touched:
 *      one written by the old raw sync (its header says so), one this script
 *      converted before (its provenance names nl-design-system/themes), or an
 *      organisation the app does not ship yet. Every other set is hand
 *      authored or hand resolved and is never written, whatever upstream does;
 *   2. builds the theme's own `design-tokens.css` the way upstream's
 *      style-dictionary config does (kebab names, references as `var()`), and
 *      runs it through `js/lib/tokenConverter.js`, the converter behind
 *      `scripts/convert-nlds-theme.mjs`, onto the nldesign vocabulary;
 *   3. carries forward the set's local overrides (for example the `--denhaag-*`
 *      values and the footer band of #899 and #979): declarations the old file
 *      has that neither upstream nor the converter produce;
 *   4. lets the tests decide. All candidates go in together and the gate
 *      (`scripts/token-set-gate.sh`: dark variants, contrast report, token
 *      reference, the shipped-set PHPUnit tests) runs once. When it fails, the
 *      sets are retried one at a time and a set that fails the gate on its own
 *      is put back exactly as it was and listed with the failing tests.
 *
 * A set that cannot be converted cleanly is left unchanged and named in the
 * report, which the workflow uses as the PR body
 * (openspec/specs/token-sync-workflow/spec.md).
 *
 * Usage:
 *   node scripts/sync-upstream-tokens.mjs <themes-checkout> [themesCommitSha]
 *        [--report report.md] [--only a,b] [--gate "<command>"] [--no-gate]
 *        [--pin <slug>:--nldesign-<token>=<value>]...   (writes a pin into the set's local overrides)
 *
 * Exit codes: 0 done (with or without changes), 1 usage error, 2 the gate
 * still fails after every rejected set was put back (the tree is not safe to
 * open a PR from).
 *
 * @spec openspec/specs/token-sync-workflow/spec.md#requirement-converted-and-gated-sync
 */

