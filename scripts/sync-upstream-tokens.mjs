/** Header line the old raw sync wrote at the top of every file it generated. */
export const RAW_SYNC_MARKER = 'Auto-generated from nl-design-system/themes'

/** Header line the converter writes at the top of every file it generates. */
export const CONVERTER_MARKER = 'GENERATED by Thematiq TokenSetConverterService'

/** Provenance source this script passes to the converter, so a later run recognises its own output. */
export const SOURCE_PREFIX = 'nl-design-system/themes proprietary/'

/** Opening line of the section that holds a set's carried-forward local overrides. */
export const OVERRIDES_HEADING = '/* 5. Local overrides, kept by the token sync'

/** Paths a candidate can change, relative to the repo root. */
const ALLOWLIST_PATH = 'tests/Unit/fixtures/token-set-vocabulary-allowlist.json'
const MANIFEST_PATH = 'token-sets.json'

/**
 * Split a path into the words lodash's kebabCase sees (style-dictionary's
 * `name/kebab`): camel humps, letter and digit runs, anything else a break.
 *
 * @param {Array<string>} path Token path segments.
 * @return {string} The kebab name, without the leading `--`.
 */
export function kebabName(path) {
	return path
		.join(' ')
		.replace(/([a-z])([A-Z])/g, '$1 $2')
		.replace(/([A-Za-z])([0-9])/g, '$1 $2')
		.replace(/([0-9])([A-Za-z])/g, '$1 $2')
		.split(/[^A-Za-z0-9]+/)
		.filter((word) => word !== '')
		.join('-')
		.toLowerCase()
}

/**
 * Deep-merge token documents the way style-dictionary merges its sources.
 *
 * @param {Object} target Merged so far (mutated).
 * @param {Object} source One parsed token file.
 * @return {Object} The target.
 */
export function mergeTokens(target, source) {
	for (const [key, value] of Object.entries(source)) {
		const isLeaf =
			value !== null
			&& typeof value === 'object'
			&& ('value' in value || '$value' in value)
		if (
			value !== null
			&& typeof value === 'object'
			&& Array.isArray(value) === false
			&& isLeaf === false
			&& target[key] !== null
			&& typeof target[key] === 'object'
		) {
			mergeTokens(target[key], value)
		} else {
			target[key] = value
		}
	}
	return target
}

/**
 * Render a token value as CSS, references as `var()` (`outputReferences`).
 *
 * @param {*} value A leaf value.
 * @return {string|null} The CSS value, or null for a composite it cannot express.
 */
export function cssValue(value) {
	if (Array.isArray(value)) {
		return value.map((part) => String(part)).join(', ')
	}
	if (value === null || typeof value === 'object') {
		return null
	}
	const text = String(value).trim()
	if (text === '') {
		return null
	}
	return text.replace(
		/\{([^{}]+)\}/g,
		(match, ref) => `var(--${kebabName(ref.split('.'))})`,
	)
}

/**
 * Build the theme's `design-tokens.css`: one class-scoped block of custom
 * properties, which is the built-theme input the converter is made for.
 *
 * @param {Object} tokens The merged token tree.
 * @param {string} prefix The theme prefix (`config.prefix`).
 * @return {string} The CSS.
 */
export function buildThemeCss(tokens, prefix) {
	const lines = []
	const walk = (node, path) => {
		if (node === null || typeof node !== 'object') {
			return
		}
		if ('value' in node || '$value' in node) {
			const value = cssValue(node.value ?? node.$value)
			if (value !== null) {
				lines.push(`\t--${kebabName(path)}: ${value};`)
			}
			return
		}
		for (const key of Object.keys(node)) {
			if (key.startsWith('$') === false && key !== 'comment') {
				walk(node[key], [...path, key])
			}
		}
	}
	walk(tokens, [])
	lines.sort()
	return `.${prefix}-theme {\n${lines.join('\n')}\n}\n`
}

/**
 * Which kind of set a shipped file is, as far as the sync is concerned.
 *
 * @param {string|null} css The shipped css/tokens/<slug>.css, or null.
 * @param {boolean} inManifest Whether token-sets.json has an entry for the slug.
 * @return {string} `new`, `raw-sync`, `converted` or `hand`.
 */
export function classifySet(css, inManifest) {
	if (css === null) {
		return inManifest === true ? 'hand' : 'new'
	}
	const head = css.split('\n').slice(0, 15).join('\n')
	if (head.includes(RAW_SYNC_MARKER)) {
		return 'raw-sync'
	}
	if (
		head.includes(CONVERTER_MARKER)
		&& css.includes(`source:          ${SOURCE_PREFIX}`)
	) {
		return 'converted'
	}
	return 'hand'
}

/**
 * The custom-property declarations of a file, last one wins, comments removed.
 *
 * @param {string} css The CSS.
 * @return {Map<string, string>} Name to value.
 */
export function declarations(css) {
	const out = new Map()
	const stripped = css.replace(/\/\*[\s\S]*?\*\//g, '')
	for (const match of stripped.matchAll(/(--[A-Za-z0-9_-]+)\s*:\s*([^;]*);/g)) {
		out.set(match[1], match[2].trim())
	}
	return out
}

/**
 * The local overrides of a shipped set: what a person added on top of the sync.
 *
 * For a converted set that is exactly its overrides section. For a raw-sync
 * set it is every declaration the raw dump of the same upstream would not have
 * written (rawNames), minus what the new conversion declares itself.
 *
 * @param {string} oldCss The shipped file.
 * @param {string} kind `raw-sync` or `converted`.
 * @param {Set<string>} rawNames Names the raw dump writes for this organisation.
 * @param {Map<string, string>} candidate The new conversion's declarations.
 * @return {Array<Array<string>>} `[name, value]` pairs, in file order.
 */
export function localOverrides(oldCss, kind, rawNames, candidate) {
	let source = oldCss
	if (kind === 'converted') {
		const start = oldCss.indexOf(OVERRIDES_HEADING)
		if (start === -1) {
			return []
		}
		source = oldCss.slice(start)
	}
	const out = []
	for (const [name, value] of declarations(source)) {
		if (kind === 'raw-sync' && rawNames.has(name)) {
			continue
		}
		if (kind === 'raw-sync' && candidate.has(name)) {
			continue
		}
		out.push([name, value])
	}
	return out
}

/**
 * Append the overrides section inside the converted file's `:root` block.
 *
 * @param {string} css The converter's output.
 * @param {Array<Array<string>>} overrides `[name, value]` pairs.
 * @return {string} The CSS with the section, or unchanged when there is none.
 */
export function withOverrides(css, overrides) {
	if (overrides.length === 0) {
		return css
	}
	const close = css.lastIndexOf('}')
	const block = [
		'',
		`\t${OVERRIDES_HEADING}: values a person set on top of upstream.`,
		'\t *    The sync carries them into every run; edit them here, nowhere else. */',
		...overrides.map(([name, value]) => `\t${name}: ${value};`),
	].join('\n')
	return (
		css.slice(0, close).replace(/\s*$/, '')
		+ '\n'
		+ block
		+ '\n'
		+ css.slice(close)
	)
}

/**
 * Parse the command line.
 *
 * @param {Array<string>} argv Raw arguments.
 * @return {Object} Options.
 */
function parseArgs(argv) {
	const options = {
		themes: null,
		sha: process.env.THEMES_COMMIT_SHA || null,
		report: null,
		only: null,
		gate: 'bash scripts/token-set-gate.sh',
		runGate: true,
		pins: {},
	}
	const positional = []
	for (let index = 0; index < argv.length; index++) {
		const arg = argv[index]
		if (arg === '--no-gate') {
			options.runGate = false
		} else if (arg === '--report' || arg === '--only' || arg === '--gate') {
			const value = argv[++index]
			if (value === undefined) {
				throw new Error(`${arg} needs a value.`)
			}
			options[arg.slice(2)] =
				arg === '--only' ? value.split(',').map((id) => id.trim()) : value
		} else if (arg === '--pin') {
			const pin = /^([a-z0-9-]+):(--nldesign-[\w-]+)=(.+)$/.exec(
				argv[++index] ?? '',
			)
			if (pin === null) {
				throw new Error('--pin needs <slug>:--nldesign-<token>=<value>.')
			}
			options.pins[pin[1]] = {
				...(options.pins[pin[1]] ?? {}),
				[pin[2]]: pin[3],
			}
		} else if (arg.startsWith('--')) {
			throw new Error(`Unknown option ${arg}.`)
		} else {
			positional.push(arg)
		}
	}
	options.themes = positional[0] ?? null
	if (positional[1] !== undefined) {
		options.sha = positional[1]
	}
	return options
}

/**
 * Read a repo file, or null when it does not exist.
 *
 * @param {string} path Relative path.
 * @return {string|null} The content.
 */
function readRepo(path) {
	const full = join(REPO_ROOT, path)
	return existsSync(full) ? readFileSync(full, 'utf8') : null
}

/**
 * Write a repo file, or delete it when content is null.
 *
 * @param {string} path Relative path.
 * @param {string|null} content The content.
 * @return {void}
 */
function writeRepo(path, content) {
	const full = join(REPO_ROOT, path)
	if (content === null) {
		rmSync(full, { force: true })
		return
	}
	mkdirSync(dirname(full), { recursive: true })
	writeFileSync(full, content, 'utf8')
}

/**
 * The `--nldesign-color-*` values a person pinned in a converted set's local overrides
 * (for example the committed primary of nijmegen, Ruben's decision on #996). The
 * converter keeps them over its rules and its contrast repair, and repairs only
 * the colours that depend on them, so the emitted set agrees with the overrides
 * the file carries forward.
 *
 * @param {Object} org The organisation, with `oldCss` and `kind`.
 * @return {Object<string,string>} Name => pinned value.
 */
export function pinnedValues(org) {
	if (org.oldCss === null || org.kind !== 'converted') {
		return { ...(org.extraPins ?? {}) }
	}
	return {
		...Object.fromEntries(
			localOverrides(org.oldCss, 'converted', new Set(), new Map()).filter(
				([name]) => name.startsWith('--nldesign-color-'),
			),
		),
		...(org.extraPins ?? {}),
	}
}

/**
 * Write pins given on the command line (`--pin`) into the set's local overrides,
 * replacing an override of the same name. From then on the overrides section is
 * their home and every later run carries them forward without the flag.
 *
 * @param {string} css The converted set, possibly with an overrides section.
 * @param {Object<string,string>} pins Name => value.
 * @return {string} The set with the pins in its overrides section.
 */
export function withPins(css, pins) {
	const names = Object.keys(pins)
	if (names.length === 0) {
		return css
	}
	const kept = localOverrides(css, 'converted', new Set(), new Map()).filter(
		([name]) => names.includes(name) === false,
	)
	let base = css
	const start = css.indexOf(OVERRIDES_HEADING)
	if (start !== -1) {
		base =
			css.slice(0, css.lastIndexOf('\n', start)).replace(/\s*$/, '') + '\n}\n'
	}
	return withOverrides(base, [...names.map((name) => [name, pins[name]]), ...kept])
}

/**
 * Give a theme without any primary token the set's committed primary colour.
 *
 * The converter's primary rule falls back to the manifest's `theming.primary_color`,
 * which only the server runtime can read. A few upstream themes (buren, venray) have
 * no primary token at all, so the sync hands the committed colour in as the theme's
 * own `--{slug}-color-primary`, the rule's second source.
 * A set this script converted before carries that value in its palette section,
 * and the sync hands that one back, not the manifest's: the manifest holds the
 * repaired primary, and feeding it back would move the derived colours once more.
 *
 * @param {string} css The built theme CSS.
 * @param {Object} org The organisation, with `slug` and `manifestPrimary`.
 * @return {string} The CSS, with the primary added when the theme had none.
 */
export function withManifestPrimary(css, org) {
	const primary = org.manifestPrimary
	if (
		typeof primary !== 'string'
		|| /^#[0-9a-f]{6}$/i.test(primary) === false
		|| /--utrecht-button-primary-action-background-color\s*:/.test(css)
		|| new RegExp(`--${org.slug}-color-primary\\s*:`).test(css)
	) {
		return css
	}
	const close = css.lastIndexOf('}')
	return `${css.slice(0, close)}\t--${org.slug}-color-primary: ${primary.toLowerCase()};\n${css.slice(close)}`
}

/**
 * Convert one organisation into a candidate, or say why it cannot be.
 *
 * @param {Object} org `{dir, slug, name, prefix, version, kind, oldCss}`.
 * @param {Object} context Converter context.
 * @return {Object} `{ok: true, css, entry}` or `{ok: false, reason}`.
 */
function convertOrg(org, context) {
	const tokenFiles = findTokenFiles(join(org.dir, 'src'))
	if (tokenFiles.length === 0) {
		const figma = existsSync(join(org.dir, 'figma'))
		return {
			ok: false,
			reason: figma
				? 'upstream now publishes only a Tokens Studio export (figma/), which the sync does not convert yet'
				: 'no *.tokens.json files upstream',
		}
	}
	const merged = {}
	const rawTokens = []
	for (const file of tokenFiles.sort()) {
		let json
		try {
			json = JSON.parse(readFileSync(file, 'utf8'))
		} catch (error) {
			return {
				ok: false,
				reason: `malformed upstream JSON in ${relative(org.dir, file)}: ${error.message}`,
			}
		}
		mergeTokens(merged, json)
		rawTokens.push(...flattenTokens(json))
	}

	let result
	try {
		result = context.converter.convert(
			withManifestPrimary(buildThemeCss(merged, org.prefix), org),
			{
				slug: org.slug,
				displayName: org.name,
				sourceName: SOURCE_PREFIX + org.dirName,
				sourceVersion: org.version,
				table: context.table,
				tableHash: context.tableHash,
				vocabulary: context.vocabulary,
				fonts: [],
				repairContrast: true,
				pinned: pinnedValues(org),
			},
		)
	} catch (error) {
		return { ok: false, reason: `converter refused the theme: ${error.message}` }
	}

	// A logo is a curated, inventoried asset (img/ICONS.md, IconAssetsTest): the
	// sync keeps a shipped one and never adds one on its own.
	if (result.logoAsset) {
		if (existsSync(join(REPO_ROOT, result.logoAsset.path)) === false) {
			return {
				ok: false,
				reason: `the theme carries a logo the app does not ship yet (${result.logoAsset.path}); add it to img/logos and img/ICONS.md by hand first`,
			}
		}
	}

	// The manifest colours reach Nextcloud's own theming. The converter copies
	// them from the theme as written, so an upstream typo (demodam's page
	// background `F5FaFD`, no `#`) would land there verbatim.
	for (const key of ['primary_color', 'background_color']) {
		const value = result.manifestEntry.theming?.[key]
		if (
			value !== undefined
			&& /^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i.test(String(value)) === false
		) {
			return {
				ok: false,
				reason: `the theme's ${key} is not a colour (\`${value}\`); fix it upstream or set it by hand`,
			}
		}
	}

	let css = result.css
	if (org.oldCss !== null) {
		const rawNames = new Set(
			declarations(
				generateOrgCSS(org.slug, org.name, rawTokens, [
					org.slug,
					org.slug.replace(/-/g, ''),
					org.prefix,
				]),
			).keys(),
		)
		css = withOverrides(
			css,
			localOverrides(org.oldCss, org.kind, rawNames, declarations(css)),
		)
	}

	css = withPins(css, org.extraPins ?? {})

	return { ok: true, css, entry: result.manifestEntry }
}

/**
 * Merge a converted entry into the manifest without losing what a person set.
 *
 * Name, description, design system and every field the converter does not
 * produce stay as committed; the converter's theming values win where both
 * exist, because they come from the set file the test compares them to.
 *
 * @param {Array<Object>} manifest The manifest (mutated).
 * @param {Object} entry The converter's entry.
 * @param {Object} org The organisation.
 * @param {string|null} sha The themes commit.
 * @return {void}
 */
function mergeEntry(manifest, entry, org, sha) {
	const provenance = {}
	if (sha) {
		provenance.upstreamRef = sha
	}
	if (org.version) {
		provenance.upstreamVersion = org.version
	}
	const index = manifest.findIndex((existing) => existing.id === org.slug)
	if (index === -1) {
		manifest.push({
			id: org.slug,
			name: org.name,
			description: `Design tokens for ${org.name}, converted from nl-design-system/themes`,
			design_system: 'nldesign',
			theming: entry.theming ?? {},
			...provenance,
		})
		return
	}
	const existing = manifest[index]
	const theming = { ...(existing.theming ?? {}), ...(entry.theming ?? {}) }
	if (existing.theming?.logo !== undefined) {
		theming.logo = existing.theming.logo
	}
	manifest[index] = { ...existing, theming, ...provenance }
}

/**
 * The Node vocabulary audit (mirror of TokenSetVocabularyAuditService).
 *
 * @return {Map<string, boolean>} Set id to complete.
 */
function vocabularyComplete() {
	const run = spawnSync(
		process.execPath,
		[join(REPO_ROOT, 'scripts/audit-token-sets.mjs'), '--json'],
		{ cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
	)
	const parsed = JSON.parse(run.stdout)
	const rows = Array.isArray(parsed) ? parsed : (parsed.results ?? [])
	return new Map(
		rows.map((row) => [
			row.id,
			row.complete === true || row.auditable === false,
		]),
	)
}

/**
 * Apply a group of candidates on top of the baseline, and tidy the allow-list.
 *
 * @param {Object} baseline `{manifest, allowlist}` as committed.
 * @param {Array<Object>} accepted Candidates to apply.
 * @param {string|null} sha The themes commit.
 * @return {void}
 */
function apply(baseline, accepted, sha) {
	const manifest = JSON.parse(baseline.manifest)
	for (const candidate of accepted) {
		writeRepo(`css/tokens/${candidate.org.slug}.css`, candidate.css)
		mergeEntry(manifest, candidate.entry, candidate.org, sha)
	}
	writeRepo(MANIFEST_PATH, JSON.stringify(manifest, null, '\t') + '\n')

	// The allow-list only shrinks: a converted set that is now complete leaves it.
	const allowlist = JSON.parse(baseline.allowlist)
	const complete = vocabularyComplete()
	const touched = new Set(accepted.map((candidate) => candidate.org.slug))
	allowlist.sets = allowlist.sets.filter(
		(id) => touched.has(id) === false || complete.get(id) !== true,
	)
	writeRepo(ALLOWLIST_PATH, JSON.stringify(allowlist, null, '\t') + '\n')
}

/**
 * Put every file a candidate group may have changed back to its baseline.
 *
 * @param {Object} baseline The baseline snapshot.
 * @return {void}
 */
function restore(baseline) {
	for (const [path, content] of baseline.files) {
		writeRepo(path, content)
	}
	writeRepo(MANIFEST_PATH, baseline.manifest)
	writeRepo(ALLOWLIST_PATH, baseline.allowlist)
}

/**
 * Run the gate command.
 *
 * @param {string} command Shell command.
 * @return {Object} `{ok, failures}`; failures names the failing tests.
 */
function runGate(command) {
	const run = spawnSync('bash', ['-c', command], {
		cwd: REPO_ROOT,
		encoding: 'utf8',
		maxBuffer: 256 * 1024 * 1024,
	})
	const output = `${run.stdout}\n${run.stderr}`
	const failures = [
		...new Set(
			[...output.matchAll(/^\d+\) (\S+)/gm)].map((match) =>
				match[1].replace(/^OCA\\Thematiq\\Tests\\Unit\\/, ''),
			),
		),
	]
	for (const match of output.matchAll(/^ FAIL +(\S+)/gm)) {
		if (failures.includes(match[1]) === false) {
			failures.push(match[1])
		}
	}
	if (run.status !== 0 && failures.length === 0) {
		failures.push(output.trim().split('\n').slice(-3).join(' ').slice(0, 300))
	}
	return { ok: run.status === 0, failures, output }
}

/**
 * Write the markdown report the workflow uses as the PR body.
 *
 * @param {Object} summary Outcome lists.
 * @param {Object} options Options.
 * @return {string} The markdown.
 */
function renderReport(summary, options) {
	const lines = []
	lines.push(
		'Converted from [nl-design-system/themes](https://github.com/nl-design-system/themes)'
			+ (options.sha ? ` at \`${options.sha}\`` : '')
			+ ' by `scripts/sync-upstream-tokens.mjs`.',
	)
	lines.push(
		'Every changed set went through the converter and passed the token-set gate (`scripts/token-set-gate.sh`).',
	)
	lines.push('')
	const section = (title, rows) => {
		lines.push(`### ${title} (${rows.length})`)
		lines.push(rows.length === 0 ? '- none' : rows.join('\n'))
		lines.push('')
	}
	section(
		'Changed',
		summary.changed.map(
			(row) =>
				`- \`${row.slug}\`${row.version ? ` ${row.version}` : ''}${row.isNew ? ' (new)' : ''}${row.overrides > 0 ? `, ${row.overrides} local overrides kept` : ''}${row.primary ? `, primary colour ${row.primary}` : ''}`,
		),
	)
	section(
		'Left unchanged: could not be converted cleanly',
		summary.rejected
			.filter((row) => row.shipped)
			.map((row) => `- \`${row.slug}\`: ${row.reason}`),
	)
	section(
		'Not added: new upstream organisations that could not be converted cleanly',
		summary.rejected
			.filter((row) => row.shipped === false)
			.map((row) => `- \`${row.slug}\`: ${row.reason}`),
	)
	section(
		'Not touched: hand authored or hand resolved',
		summary.hand.map((slug) => `- \`${slug}\``),
	)
	lines.push(
		`Unchanged after conversion: ${summary.same.length === 0 ? 'none' : summary.same.map((slug) => `\`${slug}\``).join(', ')}.`,
	)
	lines.push('')
	return lines.join('\n')
}

/**
 * Entry point.
 *
 * @return {number} Exit code.
 */
function main() {
	let options
	try {
		options = parseArgs(process.argv.slice(2))
	} catch (error) {
		console.error(`[${LABEL}] ${error.message}`)
		return 1
	}
	if (
		options.themes === null
		|| existsSync(join(resolve(options.themes), 'proprietary')) === false
	) {
		console.error(
			`[${LABEL}] usage: node scripts/sync-upstream-tokens.mjs <themes-checkout> [sha] [--report out.md] [--only a,b] [--no-gate]`,
		)
		return 1
	}

	const tablePath = join(REPO_ROOT, 'scripts/mapping/nlds-to-nextcloud.json')
	const tableRaw = readFileSync(tablePath, 'utf8')
	const converter = require(join(REPO_ROOT, 'js/lib/tokenConverter.js'))
	const context = {
		converter,
		table: JSON.parse(tableRaw),
		tableHash: createHash('sha256').update(tableRaw).digest('hex'),
		vocabulary: converter.vocabularyFrom([
			readFileSync(
				join(REPO_ROOT, 'css/systems/nldesign/defaults.css'),
				'utf8',
			),
			readFileSync(
				join(REPO_ROOT, 'css/systems/nldesign/utrecht-bridge.css'),
				'utf8',
			),
		]),
	}

	const baseline = {
		manifest: readRepo(MANIFEST_PATH),
		allowlist: readRepo(ALLOWLIST_PATH),
		files: new Map(),
	}
	const manifestIds = new Set(
		JSON.parse(baseline.manifest).map((entry) => entry.id),
	)
	const manifestPrimaries = new Map(
		JSON.parse(baseline.manifest).map((entry) => [
			entry.id,
			entry.theming?.primary_color,
		]),
	)
	const proprietary = join(resolve(options.themes), 'proprietary')
	const summary = { changed: [], rejected: [], hand: [], same: [] }
	const candidates = []

	for (const dirName of readdirSync(proprietary).sort()) {
		const dir = join(proprietary, dirName)
		if (dirName.startsWith('.') || statSync(dir).isDirectory() === false) {
			continue
		}
		const slug = extractOrgId(dirName)
		if (options.only !== null && options.only.includes(slug) === false) {
			continue
		}
		const config = readOrgConfig(dir) ?? {}
		const oldCss = readRepo(`css/tokens/${slug}.css`)
		const kind = classifySet(oldCss, manifestIds.has(slug))
		if (kind === 'hand') {
			summary.hand.push(slug)
			console.log(`  HAND ${slug}: hand authored, not touched`)
			continue
		}
		const org = {
			dir,
			dirName,
			slug,
			kind,
			oldCss,
			name: config.fullName || config.name || slug,
			prefix: config.prefix || slug,
			version: readOrgVersion(dir, config),
			manifestPrimary:
				(kind === 'converted'
					? declarations(oldCss).get(`--${slug}-color-primary`)
					: undefined)
				?? manifestPrimaries.get(slug)
				?? null,
			extraPins: options.pins[slug] ?? {},
		}
		const converted = convertOrg(org, context)
		if (converted.ok === false) {
			summary.rejected.push({
				slug,
				reason: converted.reason,
				shipped: kind !== 'new',
			})
			console.log(`  SKIP ${slug}: ${converted.reason}`)
			continue
		}
		if (converted.css === oldCss) {
			summary.same.push(slug)
			continue
		}
		baseline.files.set(`css/tokens/${slug}.css`, oldCss)
		baseline.files.set(
			`css/tokens/dark/${slug}.css`,
			readRepo(`css/tokens/dark/${slug}.css`),
		)
		candidates.push({
			org,
			css: converted.css,
			entry: converted.entry,
			overrides: (converted.css.split(OVERRIDES_HEADING)[1] ?? '')
				.split('\n')
				.filter((line) => /^\t--/.test(line)).length,
		})
		console.log(`  CONV ${slug} (${kind})`)
	}

	// New sets must be vocabulary complete: the allow-list never grows.
	let accepted = candidates
	if (accepted.length > 0) {
		apply(baseline, accepted, options.sha)
		const complete = vocabularyComplete()
		const incomplete = accepted.filter(
			(candidate) =>
				candidate.org.kind === 'new'
				&& complete.get(candidate.org.slug) !== true,
		)
		for (const candidate of incomplete) {
			summary.rejected.push({
				slug: candidate.org.slug,
				reason: 'the conversion is not vocabulary complete (scripts/audit-token-sets.mjs), and a new set may not join the allow-list',
				shipped: false,
			})
		}
		accepted = accepted.filter(
			(candidate) => incomplete.includes(candidate) === false,
		)
		restore(baseline)
	}

	if (options.runGate === true) {
		apply(baseline, accepted, options.sha)
		let gate = runGate(options.gate)
		if (gate.ok === false && accepted.length > 0) {
			console.log(
				`[${LABEL}] gate failed with every candidate in (${gate.failures.join(', ')}); retrying one set at a time`,
			)
			restore(baseline)
			const kept = []
			for (const candidate of accepted) {
				apply(baseline, [...kept, candidate], options.sha)
				const single = runGate(options.gate)
				if (single.ok === true) {
					kept.push(candidate)
					console.log(`  OK   ${candidate.org.slug}`)
				} else {
					summary.rejected.push({
						slug: candidate.org.slug,
						reason: `fails the gate: ${single.failures.slice(0, 6).join(', ')}`,
						shipped: candidate.org.kind !== 'new',
					})
					console.log(
						`  FAIL ${candidate.org.slug}: ${single.failures.join(', ')}`,
					)
				}
				restore(baseline)
			}
			accepted = kept
			apply(baseline, accepted, options.sha)
			gate = runGate(options.gate)
		}
		if (gate.ok === false) {
			console.error(gate.output.split('\n').slice(-40).join('\n'))
			console.error(
				`[${LABEL}] the gate fails even with every rejected set put back: ${gate.failures.join(', ')}`,
			)
			return 2
		}
	} else {
		apply(baseline, accepted, options.sha)
	}

	const before = new Map(
		JSON.parse(baseline.manifest).map((entry) => [
			entry.id,
			entry.theming?.primary_color,
		]),
	)
	for (const candidate of accepted) {
		const oldPrimary = before.get(candidate.org.slug)
		const newPrimary = candidate.entry.theming?.primary_color
		const primary =
			oldPrimary !== undefined
			&& newPrimary !== undefined
			&& String(oldPrimary).toLowerCase() !== String(newPrimary).toLowerCase()
				? `${oldPrimary} to ${newPrimary}`
				: null
		summary.changed.push({
			slug: candidate.org.slug,
			version: candidate.org.version,
			isNew: candidate.org.kind === 'new',
			overrides: candidate.overrides,
			primary,
		})
	}
	summary.rejected.sort((left, right) => left.slug.localeCompare(right.slug))

	const report = renderReport(summary, options)
	if (options.report !== null) {
		writeFileSync(resolve(options.report), report, 'utf8')
	}
	console.log(`\n${report}`)
	return 0
}

if (
	process.argv[1] !== undefined
	&& resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
	process.exitCode = main()
}
