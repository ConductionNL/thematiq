const flush = () => new Promise((resolve) => setTimeout(resolve, 0))

let added = []

/**
 * Load the panels and the set panel, then open a hash.
 *
 * @param {string} hash The hash to open.
 */
async function openAt(hash) {
	for (const target of [window, document]) {
		const original = target.addEventListener.bind(target)
		vi.spyOn(target, 'addEventListener').mockImplementation((type, listener, options) => {
			added.push([target, type, listener])
			original(type, listener, options)
		})
	}
	vi.resetModules()
	await import('../../js/admin-panels.js?t=' + Math.random())
	await import('../../js/admin-token-set-panel.js?t=' + Math.random())
	window.history.replaceState(null, '', hash)
	window.dispatchEvent(new HashChangeEvent('hashchange'))
	await flush()
	await flush()
}

describe('token set panel', () => {
	beforeEach(() => {
		window.t = (app, text, vars) => String(text).replace(/\{(\w+)\}/g, (all, key) => (vars && key in vars ? String(vars[key]) : all))
		window.OC = { linkTo: (app, path) => '/apps/' + app + '/' + path, generateUrl: (path) => '/index.php' + path }
		window.OCP = { InitialState: { loadState: (app, key) => ({ tokenSets: SETS, currentTokenSet: 'zuiddrecht' })[key] } }
		window.scrollTo = vi.fn()
		global.fetch = vi.fn((url) => Promise.resolve({
			ok: url.indexOf('utrecht') === -1 || url.indexOf('zuiddrecht') !== -1,
			text: () => Promise.resolve(url.indexOf('/dark/') !== -1 ? DARK : LIGHT),
		}))
		document.body.innerHTML = PAGE
		window.history.replaceState(null, '', window.location.pathname)
	})

	afterEach(() => {
		vi.restoreAllMocks()
		added.forEach(([target, type, listener]) => target.removeEventListener(type, listener))
		added = []
		window.history.replaceState(null, '', window.location.pathname)
		document.body.innerHTML = ''
		delete window.ThematiqPanels
		delete document.documentElement.dataset.thematiqOpenPanel
	})

	it('opens on #set/<id> and reads that set\'s token files', async () => {
		await openAt('#set/zuiddrecht')
		expect(document.querySelector('[data-thematiq-panel="set"]').hidden).toBe(false)
		expect(window.ThematiqPanels.current()).toBe('set')
		expect(window.ThematiqPanels.argument()).toBe('zuiddrecht')
		const urls = global.fetch.mock.calls.map((call) => call[0])
		expect(urls).toEqual(['/apps/thematiq/css/tokens/zuiddrecht.css', '/apps/thematiq/css/tokens/dark/zuiddrecht.css'])
	})

	it('titles the header with the set and sums it up under the breadcrumb', async () => {
		await openAt('#set/zuiddrecht')
		expect(document.querySelector('.thematiq-page-header__title').textContent).toBe('Gemeente Zuiddrecht')
		const crumbs = [...document.querySelectorAll('.thematiq-page-header__crumbs > :not([aria-hidden])')].map((el) => el.textContent)
		expect(crumbs.slice(-2)).toEqual(['Token sets', 'zuiddrecht'])
		const intro = document.querySelector('.thematiq-page-header__intro').textContent
		expect(intro).toContain('Active')
		expect(intro).toContain('Light and dark')
		expect(intro).toContain('NL Design System, 16 tokens, Fira Sans')
	})

	it('offers Use this token set only for a set that is not active', async () => {
		await openAt('#set/zuiddrecht')
		expect(document.querySelector('.thematiq-set-panel__use')).toBeNull()
		window.history.replaceState(null, '', '#set/utrecht')
		window.dispatchEvent(new HashChangeEvent('hashchange'))
		await flush()
		const use = document.querySelector('.thematiq-set-panel__use')
		expect(use).not.toBeNull()
		const picker = document.getElementById('nldesign-token-set-select')
		const changed = vi.fn()
		picker.addEventListener('change', changed)
		use.click()
		expect(picker.value).toBe('utrecht')
		expect(changed).toHaveBeenCalledTimes(1)
	})

	it('opens the More menu with the reference and its download, and Escape closes it', async () => {
		await openAt('#set/zuiddrecht')
		const more = document.querySelector('.thematiq-set-panel__more')
		more.click()
		const menu = document.getElementById('thematiq-set-panel-menu')
		expect(menu.hidden).toBe(false)
		expect(more.getAttribute('aria-expanded')).toBe('true')
		const links = [...menu.querySelectorAll('a')].map((a) => a.getAttribute('href'))
		expect(links).toEqual([
			'/index.php/apps/thematiq/api/token-sets/zuiddrecht/reference?format=html',
			'/index.php/apps/thematiq/api/token-sets/zuiddrecht/reference?format=md&download=1',
		])
		expect(document.activeElement).toBe(menu.firstChild)
		menu.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))
		expect(menu.hidden).toBe(true)
		expect(document.activeElement).toBe(more)
	})

	it('lists the colours in their groups with their contrast on white', async () => {
		await openAt('#set/zuiddrecht')
		const titles = [...document.querySelectorAll('.thematiq-set-panel__group-title')].map((el) => el.textContent)
		expect(titles).toEqual(['Surface', 'Ink', 'Action', 'Accent', 'Other colours'])
		const rows = [...document.querySelectorAll('.thematiq-set-panel__row')]
		const text = rows.find((row) => row.textContent.includes('--nldesign-color-text'))
		expect(text.querySelector('.thematiq-set-panel__pill--pass').textContent).toBe('17.1 : 1')
		const link = rows.find((row) => row.textContent.includes('--nldesign-color-link'))
		expect(link.querySelector('.thematiq-set-panel__value').textContent).toBe('#3669A5')
		const onPrimary = rows.find((row) => row.textContent.includes('--nldesign-color-primary-text'))
		expect(onPrimary.textContent).toContain('5.6 : 1 on action')
		const surface = rows.find((row) => row.textContent.includes('--zuiddrecht-color-surface'))
		expect(surface.querySelector('.thematiq-set-panel__label').textContent).toBe('Surface')
		expect(surface.querySelector('.thematiq-set-panel__pill--surface').textContent).toBe('Surface, 1.1 : 1')
	})

	it('says which colours fall short on white', async () => {
		await openAt('#set/zuiddrecht')
		const summary = document.querySelector('.thematiq-set-panel__summary')
		expect(summary.textContent).toBe('1 colour falls short on white')
		expect(summary.classList.contains('thematiq-set-panel__summary--warn')).toBe(true)
		const border = [...document.querySelectorAll('.thematiq-set-panel__row')].find((row) => row.textContent.includes('--nldesign-color-border-dark'))
		expect(border.querySelector('.thematiq-set-panel__pill--warn')).not.toBeNull()
	})

	it('counts the tokens per tab and switches tabs with a click and the arrow keys', async () => {
		await openAt('#set/zuiddrecht')
		const tabs = [...document.querySelectorAll('.thematiq-set-panel__tab')]
		expect(tabs.map((tab) => tab.getAttribute('aria-label'))).toEqual([
			'Colours, 9 tokens', 'Typography, 1 token', 'Shape, 4 tokens', 'Components, 1 token', 'Website, 1 token',
		])
		document.getElementById('thematiq-set-tab-website').click()
		expect(document.getElementById('thematiq-set-tab-website').getAttribute('aria-selected')).toBe('true')
		expect(document.querySelector('.thematiq-set-panel__groups').textContent).toContain('--nldesign-website-heading-1-font-size')
		document.querySelector('.thematiq-set-panel__tabs').dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }))
		expect(document.activeElement.id).toBe('thematiq-set-tab-colours')
	})

	it('searches name, variable and value', async () => {
		await openAt('#set/zuiddrecht')
		const search = document.querySelector('.thematiq-set-panel__search')
		search.value = '#a30000'
		search.dispatchEvent(new Event('input'))
		const rows = [...document.querySelectorAll('.thematiq-set-panel__row code.thematiq-set-panel__token')].map((el) => el.textContent)
		expect(rows).toEqual(['--nldesign-component-navigation-active-color'])
		search.value = 'nothing like it'
		search.dispatchEvent(new Event('input'))
		expect(document.querySelector('.thematiq-set-panel__empty').textContent).toBe('No token matches the search.')
	})

	it('names the set\'s facts, its brand stripe and its links', async () => {
		await openAt('#set/zuiddrecht')
		const facts = [...document.querySelectorAll('.thematiq-set-panel__facts dd')].map((el) => el.textContent)
		expect(facts).toEqual(['NL Design System', 'Light workplace, menu 264 px', 'zuiddrecht.svg and a dark version', 'Generated, version 9'])
		expect(document.querySelector('.thematiq-set-panel__stripe').hidden).toBe(false)
		expect(document.querySelector('.thematiq-set-panel__stripe-line').textContent).toBe('#CC0000, #3669A5 in 6 : 3, 5px high')
		expect(document.querySelector('.thematiq-set-panel__stripe-where').textContent).toBe('Drawn on the sign-in card')
		expect(document.querySelector('.thematiq-set-panel__dark-link').hidden).toBe(false)
		expect(document.querySelector('.thematiq-set-panel__download').getAttribute('href')).toContain('format=md&download=1')
		document.querySelector('.thematiq-set-panel__components-link').click()
		expect(document.getElementById('thematiq-set-tab-components').getAttribute('aria-selected')).toBe('true')
	})

	it('draws the sample in light and, on request, in dark', async () => {
		await openAt('#set/zuiddrecht')
		const frame = document.querySelector('.thematiq-set-panel__frame')
		expect(frame.style.getPropertyValue('--frame-button')).toBe('#3669a5')
		expect(frame.style.getPropertyValue('--frame-ink')).toBe('#1b1c1d')
		document.querySelector('.thematiq-set-panel__mode[data-mode="dark"]').click()
		expect(frame.style.getPropertyValue('--frame-ink')).toBe('#e2e3e4')
		expect(frame.style.getPropertyValue('--frame-ground')).toBe('#171a20')
		expect(document.querySelector('.thematiq-set-panel__mode[data-mode="dark"]').getAttribute('aria-pressed')).toBe('true')
	})

	it('borrows the house styles of other organisations and gives them back on close', async () => {
		await openAt('#set/zuiddrecht')
		expect(document.querySelector('[data-thematiq-slot="nldesign-set-licences"] #nldesign-set-licences')).not.toBeNull()
		window.history.replaceState(null, '', window.location.pathname)
		window.dispatchEvent(new HashChangeEvent('hashchange'))
		expect(document.querySelector('[data-thematiq-panel="set"]').hidden).toBe(true)
		expect(document.querySelector('[data-thematiq-slot="nldesign-set-licences"] #nldesign-set-licences')).toBeNull()
		expect(document.activeElement).toBe(document.getElementById('row-link'))
	})

	it('hides the dark link and the dark toggle for a set without a dark file', async () => {
		global.fetch = vi.fn((url) => Promise.resolve({ ok: url.indexOf('/dark/') === -1, text: () => Promise.resolve(LIGHT) }))
		await openAt('#set/utrecht')
		expect(document.querySelector('.thematiq-set-panel__dark-link').hidden).toBe(true)
		expect(document.querySelector('.thematiq-set-panel__mode[data-mode="dark"]').disabled).toBe(true)
		const facts = [...document.querySelectorAll('.thematiq-set-panel__facts dd')].map((el) => el.textContent)
		expect(facts).toEqual(['NL Design System', 'Follows Nextcloud', 'None, Nextcloud\'s own', 'Not generated'])
		expect(document.querySelector('.thematiq-set-panel__stripe').hidden).toBe(false)
	})
})

describe('token set panel helpers', () => {
	let helpers

	beforeEach(async () => {
		vi.resetModules()
		delete window.ThematiqPanels
		document.body.innerHTML = ''
		helpers = (await import('../../js/admin-token-set-panel.js?t=' + Math.random())).default
	})

	it('reads declarations, skipping comments and keeping the first value', () => {
		expect(helpers.declarations('/* --x: 1; */ a { --a: #fff; --a: #000; --b: 4px }')).toEqual({ '--a': '#fff', '--b': '4px' })
	})

	it('follows var() references the file declares, with their fallback otherwise', () => {
		const tokens = { '--a': 'var(--b)', '--b': 'var(--c, #123456)' }
		expect(helpers.resolve('var(--a)', tokens)).toBe('#123456')
		expect(helpers.resolve('var(--unknown)', tokens)).toBe('var(--unknown)')
	})

	it('reads hex, rgb and named colours', () => {
		expect(helpers.hex('#ABC')).toBe('#aabbcc')
		expect(helpers.hex('#3669a580')).toBe('#3669a5')
		expect(helpers.hex('rgb(54, 105, 165)')).toBe('#3669a5')
		expect(helpers.hex('white')).toBe('#ffffff')
		expect(helpers.hex('8px')).toBeNull()
	})

	it('sorts tokens into tabs and labels the ones the board does not name', () => {
		expect(helpers.tabOf('--nldesign-hero-title-color', '#fff')).toBe('website')
		expect(helpers.tabOf('--nldesign-component-heading-1-font-size', '2rem')).toBe('components')
		expect(helpers.tabOf('--nl-color-blue-light', '#eaf0f7')).toBe('colours')
		expect(helpers.tabOf('--nldesign-font-family', 'Fira Sans')).toBe('typography')
		expect(helpers.tabOf('--nldesign-border-radius', '8px')).toBe('shape')
		expect(helpers.labelOf('--nl-color-blue-light')).toBe('Blue light')
		expect(helpers.labelOf('--nldesign-border-radius-small')).toBe('Border radius small')
	})
})
