import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

const LIGHT =
	':root { --nldesign-color-text: #1B1C1D; --nldesign-color-primary-hover: #234A78; --nldesign-color-link: #3669A5; }'
const DARK = `/* GENERATED by nldesign DarkPaletteService v9 from tokens/zuiddrecht.css */
@media (prefers-color-scheme: dark) { body { --nldesign-color-background: #171a20; --nldesign-color-text: #e2e3e4; --nldesign-color-primary-hover: #234a78; --nldesign-color-link: #5b8ac2; } }`

const PAGE = `
	<section id="thematiq-page-header">
		<h1 class="thematiq-page-header__title">Themes and appearance</h1>
		<div class="thematiq-page-header__actions"></div>
		<nav class="thematiq-page-header__crumbs"></nav>
		<p class="thematiq-page-header__intro"></p>
	</section>
	<div id="nldesign-settings">
		<select id="nldesign-token-set-select"><option value="zuiddrecht" selected>Gemeente Zuiddrecht</option></select>
		<section class="thematiq-panel" data-thematiq-panel="dark" hidden>
			<div class="thematiq-dark-panel__previews"></div>
			<span class="thematiq-dark-panel__measured"></span>
			<input type="checkbox" class="thematiq-dark-panel__only-warnings">
			<div class="thematiq-dark-panel__rows"></div>
			<strong class="thematiq-dark-panel__score"></strong>
			<span class="thematiq-dark-panel__bar"><span></span></span>
			<ul class="thematiq-dark-panel__problems"></ul>
		</section>
	</div>
`

const flush = () => new Promise((resolve) => setTimeout(resolve, 0))

describe('Dark variant panel', () => {
	let added = []

	beforeEach(async () => {
		window.t = (app, text, vars) =>
			String(text).replace(/\{(\w+)\}/g, (all, key) =>
				vars && key in vars ? String(vars[key]) : all,
			)
		window.OC = { linkTo: (app, path) => '/apps/' + app + '/' + path }
		window.scrollTo = vi.fn()
		global.fetch = vi.fn((url) =>
			Promise.resolve({
				ok: true,
				text: () =>
					Promise.resolve(url.indexOf('/dark/') !== -1 ? DARK : LIGHT),
			}),
		)
		document.body.innerHTML = PAGE
		window.history.replaceState(null, '', window.location.pathname)
		for (const target of [window, document]) {
			const original = target.addEventListener.bind(target)
			vi.spyOn(target, 'addEventListener').mockImplementation(
				(type, listener, options) => {
					added.push([target, type, listener])
					original(type, listener, options)
				},
			)
		}
		vi.resetModules()
		await import('../../js/admin-panels.js?t=' + Math.random())
		await import('../../js/admin-dark-panel.js?t=' + Math.random())
		window.history.replaceState(null, '', '#dark')
		window.dispatchEvent(new HashChangeEvent('hashchange'))
		await flush()
		await flush()
	})

	afterEach(() => {
		vi.restoreAllMocks()
		added.forEach(([target, type, listener]) =>
			target.removeEventListener(type, listener),
		)
		added = []
		document.body.innerHTML = ''
		delete window.ThematiqPanels
		delete document.documentElement.dataset.thematiqOpenPanel
	})

	it('reads both token files of the active set', () => {
		const urls = global.fetch.mock.calls.map((call) => call[0])
		expect(urls).toEqual([
			'/apps/thematiq/css/tokens/zuiddrecht.css',
			'/apps/thematiq/css/tokens/dark/zuiddrecht.css',
		])
	})

	it('titles the header and names the set and the generator', () => {
		expect(
			document.querySelector('.thematiq-page-header__title').textContent,
		).toBe('Dark variant')
		const crumbs = [
			...document.querySelectorAll(
				'.thematiq-page-header__crumbs > :not([aria-hidden])',
			),
		].map((el) => el.textContent)
		expect(crumbs.slice(-3)).toEqual([
			'Token sets',
			'Gemeente Zuiddrecht',
			'Dark',
		])
		const intro = document.querySelector(
			'.thematiq-page-header__intro',
		).textContent
		expect(intro).toContain('Generated')
		expect(intro).toContain('1 contrast warning')
		expect(intro).toContain('Generator version 9')
	})

	it('lists the colours light beside dark, with their contrast on the dark background', () => {
		const rows = [
			...document.querySelectorAll(
				'.thematiq-dark-panel__row:not(.thematiq-dark-panel__row--head)',
			),
		]
		const text = rows.find((row) =>
			row.textContent.includes('--nldesign-color-text'),
		)
		expect(text.textContent).toContain('#1B1C1D')
		expect(text.textContent).toContain('#E2E3E4')
		expect(text.querySelector('.thematiq-dark-panel__pill--pass')).not.toBeNull()
		const hover = rows.find((row) =>
			row.textContent.includes('--nldesign-color-primary-hover'),
		)
		expect(hover.textContent).toContain('Not converted by the generator')
		expect(
			hover.querySelector('.thematiq-dark-panel__pill--warn'),
		).not.toBeNull()
		expect(
			document.querySelector('.thematiq-dark-panel__measured').textContent,
		).toContain('#171A20')
	})

	it('sums up the check and names what falls short', () => {
		expect(
			document.querySelector('.thematiq-dark-panel__score').textContent,
		).toBe('2 of 3')
		expect(
			document.querySelector('.thematiq-dark-panel__problems').textContent,
		).toContain('Primary on hover is not converted and stays #234A78')
	})

	it('shows only the warnings when asked', () => {
		const only = document.querySelector('.thematiq-dark-panel__only-warnings')
		only.checked = true
		only.dispatchEvent(new Event('change'))
		const rows = [
			...document.querySelectorAll(
				'.thematiq-dark-panel__row:not(.thematiq-dark-panel__row--head)',
			),
		]
		expect(rows.map((row) => row.querySelector('code').textContent)).toEqual([
			'--nldesign-color-primary-hover',
		])
	})

	it('draws the set in light and in dark', () => {
		const titles = [
			...document.querySelectorAll('.thematiq-dark-panel__preview h2'),
		].map((el) => el.textContent)
		expect(titles).toEqual(['Light', 'Dark'])
		const frames = document.querySelectorAll('.thematiq-dark-panel__frame')
		expect(frames[1].style.getPropertyValue('--frame-ground')).toBe('#171a20')
	})
})
