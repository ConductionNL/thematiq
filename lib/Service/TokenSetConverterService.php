/**
 * Turn a published design-system theme into a Nextcloud token set.
 *
 * The whole mapping lives in
 * `scripts/mapping/nlds-to-nextcloud.json` as DATA, and this service is one of
 * two thin runtimes over it (the other being `js/lib/tokenConverter.js`), so
 * the admin upload path and the CLI cannot drift apart. The table's SHA-256 is
 * written into every emitted file's provenance block, which is how a set
 * generated by an older table is spotted without running anything.
 *
 * FOUR ACCEPTED INPUTS, detected from the CONTENT and never from a file name,
 * because the primary surface is a paste that has no file name:
 *
 *  - A: built theme CSS — one or more class-scoped blocks of custom properties
 *       (`.acme-theme { --utrecht-*: …; --acme-*: …; }`), values may be `var()`
 *       chains. This is what a Style Dictionary theme package publishes as
 *       `dist/design-tokens.css` and is the primary target.
 *  - B: a W3C DTCG document (`$value`/`$type`, `{a.b.c}` aliases). Routed
 *       straight to `DesignTokensMapper`, which already owns those semantics —
 *       there is deliberately no second DTCG parser here.
 *  - C: a Style Dictionary `tokens.json` tree (nested `value` leaves).
 *  - D: an existing `:root`-scoped `--nldesign-*` token set, re-converted in
 *       ADD-ONLY mode so a hand-chosen value is never overwritten.
 *
 * WHAT COMES BACK is `{css, manifestEntry, report, inputKind, counts}`. The
 * report is the contract that matters most: every source token ends up in it
 * with an action of `applied`, `adapted`, `skipped` or `kept`, and every
 * non-`applied` entry carries a reason code that exists in the table. Nothing
 * is dropped silently, because an admin who pastes a 697-declaration theme and
 * gets 26 tokens back needs to be told what happened to the other 671.
 *
 * @phpstan-type ReportEntry array{source: string, target: string, action: string, reason: string|null, value: string|null, original?: string}
 * @phpstan-type RuleInput array{declarations: array<string, string>, byRole: array<string, string>, slug: string}
 * @phpstan-type SetSource array{slug: string, displayName: string, sourceName: string|null, sourceVersion: string|null}
 * @psalm-type   ReportEntry array{source: string, target: string, action: string, reason: string|null, value: string|null, original?: string}
 * @psalm-type   RuleInput array{declarations: array<string, string>, byRole: array<string, string>, slug: string}
 * @psalm-type   SetSource array{slug: string, displayName: string, sourceName: string|null, sourceVersion: string|null}
 *
 * @spec openspec/changes/nlds-theme-converter/specs/token-set-converter/spec.md
 *
 * @SuppressWarnings(PHPMD.ExcessiveClassLength) - one interpreter for the mapping table, kept whole on purpose: the JS mirror
 *   (js/lib/tokenConverter.js) has to agree with it byte for byte, and a boundary drawn here has to be drawn identically there or the two
 *   runtimes drift.
 * @SuppressWarnings(PHPMD.TooManyMethods) - one interpreter for the mapping table, kept whole on purpose: the JS mirror
 *   (js/lib/tokenConverter.js) has to agree with it byte for byte, and a boundary drawn here has to be drawn identically there or the two
 *   runtimes drift.
 * @SuppressWarnings(PHPMD.ExcessiveClassComplexity) - one interpreter for the mapping table, kept whole on purpose: the JS mirror
 *   (js/lib/tokenConverter.js) has to agree with it byte for byte, and a boundary drawn here has to be drawn identically there or the two
 *   runtimes drift.
 */
