	 * every one of them was being renamed into the brand palette, where nothing
	 * reads it. `css/tokens/opencatalogi.css` declares 266 of them verbatim and
	 * `css/tokens/conduction.css` 103, which is what a correct set looks like.
	 *
	 * `--conduction-` belongs here for the same reason the others do, and
	 * leaving it out was destructive: an OpenWOO-shaped theme carries ~266
	 * `--conduction-*` tokens (logos, cards, pagination, tooltips, top-nav) and
	 * every one of them was being renamed into the brand palette, where nothing
