 * `scripts/audit-token-sets.mjs` folds each set's contrast verdict into the
 * per-set coverage table it prints. Reimplementing WCAG relative luminance,
 * colour parsing and `color-mix()` in a second language to do that would be two
 * engines that can disagree about whether a set passes, which is the kind of
 * disagreement nobody notices until a published claim is wrong.
 *
 * So one engine writes two files from one `composer docs:contrast-report` run:
 * the markdown report a person reads, and this JSON the Node audit reads. This
 * renderer is a class of its own rather than a second method on
 * `ShippedTokenSetAuditService` because that class measures; rendering is a
 * separate job, and it was already at its complexity ceiling.
